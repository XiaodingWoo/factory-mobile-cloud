def _query_value(name: str, default: str = "") -> str:
    try:
        value = st.query_params.get(name, default)
    except Exception:
        return default
    if isinstance(value, list):
        return str(value[0] if value else default)
    return str(value or default)


LANGUAGE_ALIASES = {
    "en": "en",
    "english": "en",
    "zh": "zh-CN",
    "zh-cn": "zh-CN",
    "zh_cn": "zh-CN",
    "zh-hans": "zh-CN",
    "cn": "zh-CN",
    "chinese": "zh-CN",
}


def normalize_lang(value: object, default: str = "en") -> str:
    raw = str(value or "").strip()
    if not raw:
        raw = default
    normalized = LANGUAGE_ALIASES.get(raw, LANGUAGE_ALIASES.get(raw.casefold(), raw))
    if normalized in TRANSLATIONS:
        return normalized
    fallback = LANGUAGE_ALIASES.get(str(default or "").strip().casefold(), default)
    return fallback if fallback in TRANSLATIONS else "en"


def current_lang(default: str = "en") -> str:
    query_lang = normalize_lang(_query_value("lang", ""), "")
    if query_lang in TRANSLATIONS:
        st.session_state["language"] = query_lang
        return query_lang
    session_lang = normalize_lang(st.session_state.get("language", ""), "")
    if session_lang in TRANSLATIONS:
        st.session_state["language"] = session_lang
        return session_lang
    fallback = normalize_lang(default, "en")
    st.session_state["language"] = fallback
    return fallback


def language() -> str:
    return current_lang()


def t(key: str, **values: object) -> str:
    text = TRANSLATIONS.get(language(), TRANSLATIONS["en"]).get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, key)
    return text.format(**values)


def language_selector(key: str = "language_selector") -> str:
    current = language()
    options = [("language.english", "en"), ("language.chinese", "zh-CN")]
    values = [value for _, value in options]
    labels = [t(label_key) for label_key, _ in options]
    selected = st.radio(
        t("language.choose"),
        labels,
        index=values.index(normalize_lang(current)) if normalize_lang(current) in values else 0,
        horizontal=True,
        key=key,
    )
    chosen = values[labels.index(selected)]
    st.session_state["language"] = chosen
    try:
        st.query_params["lang"] = chosen
    except Exception:
        pass
    return chosen
